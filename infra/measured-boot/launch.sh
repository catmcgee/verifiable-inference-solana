#!/usr/bin/env bash
# Launch an immutable measured SNP guest without SSH or a QEMU monitor.
set -euo pipefail

VMS=${VINFER_VM_DIR:-$HOME/vms}
ROOT=${VINFER_ROOT:-$HOME/verified-inference}
OUT=${VINFER_MEASURED_PREFIX:-$VMS/vinfer-measured}
QEMU=${VINFER_QEMU:-$HOME/src/AMDSEV/usr/local/bin/qemu-system-x86_64}
BIOS=${VINFER_OVMF:-$VMS/OVMF-snp.fd}
NAME=${VINFER_MEASURED_NAME:-vinfer-measured-test}
CPUS=${VINFER_MEASURED_CPUS:-32}
RAM=${VINFER_MEASURED_RAM:-64G}
API_PORT=${VINFER_MEASURED_API_PORT:-8490}
PROXY_PORT=${VINFER_MEASURED_PROXY_PORT:-8491}
if [ -n "${VINFER_AVAILABLE_MODELS:-}" ]; then
  AVAILABLE_MODELS=$VINFER_AVAILABLE_MODELS
else
  AVAILABLE_MODELS=$(cd "$ROOT" && uv run python - <<'PY'
from server import registry

print(",".join(registry.servable_ids(registry.load())))
PY
  )
fi

ROOT_IMAGE=$OUT-root.img
ROOT_HASH_IMAGE=$OUT-root.verity
SMALL_IMAGE=${VINFER_SMALL_MODEL_IMAGE:-$VMS/models.img}
SMALL_HASH_IMAGE=$OUT-models.verity
GLM_IMAGE=${VINFER_GLM_MODEL_IMAGE:-$VMS/glm-models.img}
GLM_HASH_IMAGE=$OUT-glm.verity
KERNEL=$OUT-vmlinuz
INITRD=$OUT-initrd.img
STATE=$OUT.env

for file in \
  "$QEMU" "$BIOS" "$ROOT_IMAGE" "$ROOT_HASH_IMAGE" \
  "$SMALL_IMAGE" "$SMALL_HASH_IMAGE" "$GLM_IMAGE" "$GLM_HASH_IMAGE" \
  "$KERNEL" "$INITRD" "$STATE"; do
  test -e "$file" || { echo "missing $file" >&2; exit 2; }
done
case "$AVAILABLE_MODELS" in
  *[!a-zA-Z0-9,._-]*) echo "invalid VINFER_AVAILABLE_MODELS" >&2; exit 2 ;;
esac
if pgrep -af qemu-system | grep -F -- "-name $NAME" >/dev/null; then
  echo "$NAME is already running" >&2
  exit 2
fi
for port in "$API_PORT" "$PROXY_PORT"; do
  if ss -ltn "sport = :$port" | grep -q LISTEN; then
    echo "host port $port is already in use" >&2
    exit 2
  fi
done

# This state file is generated by build-on-host.sh and contains hashes only.
# shellcheck disable=SC1090
source "$STATE"
for value in "$ROOT_HASH" "$SMALL_HASH" "$GLM_HASH" "$KERNEL_HASH" "$INITRD_HASH"; do
  test "${#value}" -eq 64 || { echo "invalid measured artifact state" >&2; exit 2; }
done

# Catch a stale root hash before allocating a guest. Model trees remain
# fail-closed in the guest and are much too large to rescan on every launch.
veritysetup verify "$ROOT_IMAGE" "$ROOT_HASH_IMAGE" "$ROOT_HASH" >/dev/null

CMDLINE="console=ttyS0 root=/dev/mapper/vinfer-root rootfstype=ext4 ro panic=30 vinfer.root_hash=$ROOT_HASH vinfer.models_hash=$SMALL_HASH vinfer.glm_hash=$GLM_HASH vinfer.kernel_sha256=$KERNEL_HASH vinfer.initrd_sha256=$INITRD_HASH vinfer.available_models=$AVAILABLE_MODELS"
if [ -n "${VINFER_EXTRA_CMDLINE:-}" ]; then
  if ! [[ $VINFER_EXTRA_CMDLINE =~ ^[-a-zA-Z0-9,._=/:+\ ]+$ ]]; then
    echo "invalid VINFER_EXTRA_CMDLINE" >&2
    exit 2
  fi
  CMDLINE="$CMDLINE $VINFER_EXTRA_CMDLINE"
fi
SERIAL=$VMS/$NAME-serial.log
PIDFILE=$VMS/$NAME.pid
test ! -e "$PIDFILE" || mv "$PIDFILE" "$PIDFILE.$(date -u +%Y%m%dT%H%M%SZ)"
test ! -e "$SERIAL" || mv "$SERIAL" "$SERIAL.$(date -u +%Y%m%dT%H%M%SZ)"

sudo "$QEMU" \
  -name "$NAME" -enable-kvm -smp "$CPUS" -m "$RAM" \
  -machine 'q35,confidential-guest-support=sev0,memory-backend=ram0,kernel-irqchip=split' \
  -object "memory-backend-memfd,id=ram0,size=$RAM,share=true,prealloc=false" \
  -object 'sev-snp-guest,id=sev0,policy=0x30000,cbitpos=51,reduced-phys-bits=1,kernel-hashes=on' \
  -bios "$BIOS" -cpu host -kernel "$KERNEL" -initrd "$INITRD" -append "$CMDLINE" \
  -drive "file=$ROOT_IMAGE,if=virtio,format=raw,readonly=on" \
  -drive "file=$ROOT_HASH_IMAGE,if=virtio,format=raw,readonly=on" \
  -drive "file=$SMALL_IMAGE,if=virtio,format=raw,readonly=on" \
  -drive "file=$SMALL_HASH_IMAGE,if=virtio,format=raw,readonly=on" \
  -drive "file=$GLM_IMAGE,if=virtio,format=raw,readonly=on" \
  -drive "file=$GLM_HASH_IMAGE,if=virtio,format=raw,readonly=on" \
  -netdev "user,id=net0,hostfwd=tcp:127.0.0.1:$API_PORT-:8477,hostfwd=tcp:127.0.0.1:$PROXY_PORT-:8480" \
  -device virtio-net-pci,netdev=net0 \
  -display none -serial "file:$SERIAL" -monitor none \
  -daemonize -pidfile "$PIDFILE"

echo "started $NAME: measured SNP, dm-verity root/models, no SSH, api=$API_PORT proxy=$PROXY_PORT"
